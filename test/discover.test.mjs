test("the all-time chart plays an upload of the song's own version, never a remix filed under it", async () => {
  const { db, d } = setup({
    globalSongs: { s1: { artist: "Geographer", title: "Kites", plays: 351 } },
    globalTracks: {
      "1orig": { song: "s1", artist: "Geographer", title: "Kites (Original Mix)", last_play_date: 10 },
      "1remix": { song: "s1", artist: "Geographer", title: "Kites (Limousines Remix)", last_play_date: 99 }
    }
  });
  await d.refreshAllTime();
  assert.deepEqual(db.get("discover/charts/all/all").rows.map((r) => r.cid + ":" + r.t), ["orig:Kites"]);
  assert.equal(discover.pickUpload({ artist: "A", title: "B" }, { "1x": { title: "B (C Remix)", last_play_date: 5 } }), "1x", "only another version: still playable");
  assert.equal(discover.pickUpload({ artist: "A", title: "B" }, { "1x": { last_play_date: 1 }, "1y": { title: "B", last_play_date: 2 } }), "1y", "the latest played");
});

test("new releases: release dates looked up once, room plays and colours added", async () => {
  let asked = [];
  const { db, d } = setup({
    globalTracks: { "1new1": { song: "s1", first_play_date: 7 } },
    globalSongs: { s1: { plays: 4, first_play_date: 7, first_play_dj: "dj2" } },
    discoverCache: { release: { cached: { d: "2026-10-20", src: "yt" } } }
  }, {
    playlist: async (id) => ({ tracks: id === "PL2026" ? [{ cid: "new1", title: "N1", artist: "A" }, { cid: "cached", title: "C", artist: "B" }, { cid: "old1", title: "O", artist: "C" }] : [] }),
    snippets: async (ids) => {
      asked = asked.concat(ids);
      return { new1: { description: "Released on: 2026-11-06" }, old1: { publishedAt: "2025-02-01T00:00:00Z" } };
    }
  });
  await d.refreshNew();
  assert.deepEqual(asked.sort(), ["new1", "old1"]);
  const list = db.get("discover/new").tracks;
  assert.deepEqual(list.map((t) => t.cid), ["new1", "cached"]);
  assert.equal(list[0].plays, 4);
  assert.equal(list[0].dj, "dj2");
  assert.equal(list[0].djid, "u2");
  assert.equal(list[0].c, "#123456");
  assert.equal(list[1].plays, 0);
  assert.equal(db.get("discoverCache/release/old1").d, "2025-02-01");
  asked = [];
  await d.refreshNew();
  assert.deepEqual(asked, [], "dates are only looked up once");
});

test("the chat peek is written only when it changes, with the hour's count", async () => {
  const chats = { c1: { id: "u1", name: "dj1", txt: "hi", time: 1 } };
  let feed = [{ key: "f1", chatID: "c1" }];
  const { db, d } = setup({}, { feed: () => feed, chatData: async (id) => chats[id] || null });
  d.noteChat(local(2026, 11, 10) - 60000);
  d.noteChat(local(2026, 11, 10) - 2 * 3600000); // over an hour ago
  await d.refreshChat();
  const first = db.get("discover/chat");
  assert.equal(first.hour, 1);
  assert.deepEqual(first.msgs.map((m) => m.txt), ["hi"]);
  await d.refreshChat();
  assert.equal(db.get("discover/chat").at, first.at);
  chats.c2 = { id: "u2", name: "dj2", txt: "yo", time: 2 };
  feed = feed.concat({ key: "f2", chatID: "c2" });
  await d.refreshChat();
  assert.deepEqual(db.get("discover/chat").msgs.map((m) => m.txt), ["hi", "yo"]);
});

