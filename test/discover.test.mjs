test("the chat peek leaves out commands and hidden entries, and hides opted-out names", () => {
  const entries = [{ key: "f1", chatID: "c1" }, { key: "f2", chatID: "c2" }, { key: "f3", chatID: "c3", hidden: true }, { key: "f4", chatID: "c4" }, { key: "f5", chatID: "c5" }, { key: "f6", chatID: "gone" }];
  const chats = {
    c1: { id: "u1", name: "dj1", txt: "hi all", time: 1 },
    c2: { id: "u2", name: "dj2", txt: "!addme", time: 2 },
    c3: { id: "u1", name: "dj1", txt: "secret", time: 3 },
    c4: { id: "u3", name: "quiet", txt: "hello", time: 4 },
    c5: { id: "u1", name: "dj1", txt: "x".repeat(400), time: 5, botCmd: false }
  };
  const peek = discover.chatPeek(entries, chats, (uid) => uid === "u3", (uid) => (uid === "u1" ? "renamed" : null));
  assert.deepEqual(peek.map((m) => m.id), ["c1", "c4", "c5"]);
  assert.equal(peek[0].n, "renamed");
  assert.equal(peek[1].n, null);
  assert.equal(peek[1].uid, null);
  assert.equal(peek[2].txt.length, 300);
});

// ------------------------------------------------------- the publisher

function setup(data, extra = {}) {
  const db = fakeDb(data);
  const users = { u1: { username: "dj1" }, u2: { username: "dj2" }, u3: { username: "quiet", publicName: false } };
  const logs = [];
  const d = discover.createDiscover(Object.assign({
    db, now: () => local(2026, 11, 10),
    hidden: (uid) => !!(users[uid] && users[uid].publicName === false),
    uidOf: (name) => Object.keys(users).find((k) => users[k].username === name) || false,
    nameOf: (uid) => (users[uid] || {}).username || null,
    playlist: async () => ({ tracks: [] }), snippets: async () => ({}), colors: async () => ({ color: "#123456", txt: "#fff" }),
    sources: [{ year: 2026, id: "PL2026" }],
    feed: () => [], chatData: async () => null,
    log: (m) => logs.push(m)
  }, extra));
  return { db, d, logs };
}

test("the weekly chart: this week, last week finished first, with movement", async () => {
  const W44 = local(2026, 10, 28), W45 = local(2026, 11, 3);
  const playLog = {};
  let n = 0;
  const add = (s, w, x) => { playLog["p" + String(n++).padStart(3, "0")] = play(s, w, x); };
  add("A", W44); add("B", W44); add("B", W44 + 1);
  add("A", W45); add("A", W45 + 1); add("C", W45 + 2, { djid: "u3", dj: "quiet" });
  const { db, d } = setup({ playLog, globalSongs: { A: { genres: ["Nu-Disco", "Disco"] } } }, { now: () => local(2026, 11, 5) });
  await d.refreshPeriod("week");
  const last = db.get("discover/charts/week/2026-W44");
  assert.equal(last.final, true);
  assert.deepEqual(last.rows.map((r) => r.key + ":" + r.mv), ["B:new", "A:new"]);
  const now = db.get("discover/charts/week/2026-W45");
  assert.equal(now.final, false);
  assert.deepEqual(now.rows.map((r) => [r.key, r.plays, r.mv, r.wks]), [["A", 2, 1, 2], ["C", 1, "new", 1]]);
  assert.equal(now.rows[1].dj, null); // opted out
  assert.deepEqual(now.rows.map((r) => r.g || null), ["Nu-Disco", null], "each song's main genre, when the history knows it");
  assert.equal(db.get("discover/chartIds/week/2026-W45"), true);
  assert.ok(db.get("discoverCache/seen/2026-W45").B, "songs ever on the chart are kept for re-entries");
  assert.equal(JSON.stringify(now).includes("seen"), false, "visitors don't download that list");
});

