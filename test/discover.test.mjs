const require = createRequire(import.meta.url);
const discover = require("../lib/discover.js");

const local = (y, m, d, h = 12) => new Date(y, m - 1, d, h).getTime();

// ------------------------------------------------------------ periods

test("chart weeks run Monday to Monday, named by ISO week", () => {
  assert.equal(discover.weekId(local(2026, 11, 2, 0)), "2026-W45");
  assert.equal(discover.weekId(local(2026, 11, 8, 23)), "2026-W45");
  assert.equal(discover.weekId(local(2026, 11, 9, 0)), "2026-W46");
  // Friday 1 January 2027 belongs to the last week of 2026 (its Thursday is in 2026)
  assert.equal(discover.weekId(local(2027, 1, 1)), "2026-W53");
  assert.equal(discover.weekId(local(2027, 1, 4)), "2027-W01");
  const r = discover.rangeOf("week", "2026-W45");
  assert.equal(r.from, local(2026, 11, 2, 0));
  assert.equal(r.to, local(2026, 11, 9, 0));
  assert.equal(discover.previousId("week", "2027-W01"), "2026-W53");
  assert.equal(discover.previousId("month", "2026-01"), "2025-12");
  assert.equal(discover.previousId("year", "2026"), "2025");
  assert.deepEqual(discover.rangeOf("month", "2026-11"), { from: local(2026, 11, 1, 0), to: local(2026, 12, 1, 0) });
});

// --------------------------------------------------------------- charts

const play = (s, w, extra) => Object.assign({ k: "1" + s.toLowerCase(), s, a: "Artist " + s, t: "Title " + s, dj: "dj1", djid: "u1", w, p: 200, sk: false }, extra);

test("a chart counts plays (not short skips), groups a song's uploads and names who played it most", () => {
  const plays = [
    play("A", 1), play("A", 2, { k: "1other", djid: "u2", dj: "dj2" }), play("A", 3, { djid: "u2", dj: "dj2" }),
    play("B", 4), play("B", 5),
    play("C", 6), play("C", 7, { sk: true, p: 10 }), // a skip after 10 seconds doesn't count
    play("D", 8, { sk: true, p: 45 })                // a skip after 45 seconds does
  ];
  const c = discover.buildChart(plays);
  assert.equal(c.plays, 7);
  assert.equal(c.djs, 2);
  assert.deepEqual(c.rows.map((r) => r.key + ":" + r.plays), ["A:3", "B:2", "D:1", "C:1"]); // ties: most recently played first
  assert.equal(c.rows[0].dj, "dj2");                 // two of its three plays
  assert.equal(c.rows[0].cid, "a");                  // the upload played last
  assert.equal(c.rows[0].type, 1);
  const hidden = discover.buildChart(plays, { hidden: (uid) => uid === "u2" });
  assert.equal(hidden.rows[0].dj, null);
  assert.equal(hidden.rows[0].djid, null);
});

test("weekly movement: places up and down, new, back again, and weeks in a row", () => {
  const prev = { rows: [{ key: "A", wks: 3 }, { key: "B", wks: 1 }, { key: "C", wks: 2 }], seen: { A: 1, B: 1, C: 1, Z: 1 } };
  const rows = discover.withMovement([{ key: "B" }, { key: "A" }, { key: "Z" }, { key: "N" }, { key: "C" }], prev);
  assert.deepEqual(rows.map((r) => [r.key, r.mv, r.wks]), [["B", 1, 2], ["A", -1, 4], ["Z", "re", 1], ["N", "new", 1], ["C", -2, 3]]);
  const seen = discover.seenKeys(prev, rows);
  assert.ok(seen.N && seen.Z && seen.A);
});

